import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
test('repair isolated database lifecycle, authorization, atomicity and replay', async () => {
 const db = new PGlite(); let seq = 100;
 try {
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
   create table public.stores(id uuid primary key,store_code text unique,name text,is_active boolean);
   create table public.profiles(id uuid primary key,full_name text,role text,store_id uuid,is_active boolean);
   insert into stores values('${id(1)}','S01','五甲',true),('${id(2)}','S02','凱旋',true);
   insert into profiles values('${id(1)}','總部','coo',null,true),('${id(2)}','店長一','store_manager','${id(1)}',true),('${id(3)}','店長二','store_manager','${id(2)}',true),('${id(4)}','外部','external',null,true),('${id(5)}','停用','coo',null,false);`);
  await db.exec(await readFile(new URL('../supabase/drafts/repair-core.sql',import.meta.url),'utf8'));
  await db.exec(`create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb);
    alter table storage.objects enable row level security;
    grant usage on schema storage to authenticated; grant select,insert on storage.objects to authenticated;`);
  await db.exec(await readFile(new URL('../supabase/drafts/repair-attachments.sql',import.meta.url),'utf8'));
  const user = n => db.query("select set_config('test.uid',$1,false)",[n ? id(n) : '']);
  const call = async(action,payload={}) => (await db.query('select public.ops_repair_api($1,$2) result',[action,JSON.stringify(payload)])).rows[0].result;
  const write = (action,payload) => call(action,{command_id:id(seq++),...payload});
  const draft = {store:'S01',category:'冰箱',description:'無法冷藏',urgency:'business'};
  await user(2);
  await assert.rejects(call(null,{command_id:id(seq++)}),/不支援/);
  const cmd = {...draft,command_id:id(seq++)};
  let row = await call('create',cmd);
  assert.deepEqual(await call('create',cmd),row);
  await assert.rejects(call('create',{...cmd,description:'改內容'}),/請求編號/);
  await assert.rejects(write('create',{...draft,store:'S02'}),/跨店/);
  await assert.rejects(write('create',{...draft,attachments:['photo']}),/尚未啟用/);
  await assert.rejects(write('start',{id:row.id,version:1,note:'接手'}));
  await user(3);
  assert.equal((await call('list')).rows.length,0);
  await assert.rejects(call('detail',{id:row.id}),/無權/);
  await assert.rejects(write('comment',{id:row.id,version:1,note:'跨店'}));
  for (const n of [0,4,5]) { await user(n); await assert.rejects(call('list')); }
  await user(1);
  row=await write('start',{id:row.id,version:row.version,note:'安排維修',assignee:'總務',actor_name:'偽造姓名',actor_role:'ceo'});
  const startedHistory=await call('detail',{id:row.id});
  assert.equal(startedHistory.events.at(-1).actor_name,'總部');
  assert.equal(startedHistory.events.at(-1).actor_role,'coo');
  row=await write('update_work',{id:row.id,version:row.version,note:'交接',assignee:'維修窗口'});
  const reassigned=await call('detail',{id:row.id});
  assert.equal(reassigned.events.at(-1).before_state.assignee,'總務');
  assert.equal(reassigned.events.at(-1).after_state.assignee,'維修窗口');
  await assert.rejects(write('finish',{id:row.id,version:1,note:'舊版本'}),/已更新/);
  await assert.rejects(write('update_work',{id:row.id,version:row.version,note:'費用',cost:-1}));
  assert.equal((await call('detail',{id:row.id})).ticket.version,row.version);
  row=await write('finish',{id:row.id,version:row.version,note:'更換零件',cost:500});
  await assert.rejects(write('confirm',{id:row.id,version:row.version,note:'代確認'}),/僅門店/);
  await user(2);
  row=await write('reject',{id:row.id,version:row.version,note:'仍不冷'});
  assert.equal(row.status,'processing');
  await user(1); row=await write('finish',{id:row.id,version:row.version,note:'再次維修'});
  await user(2); row=await write('confirm',{id:row.id,version:row.version,note:'已恢復正常'});
  assert.equal(row.status,'completed');
  await assert.rejects(write('withdraw',{id:row.id,version:row.version,note:'刪除'}));
  await assert.rejects(write('delete',{id:row.id,version:row.version,note:'刪除'}));
  const history=await call('detail',{id:row.id});
  assert.equal(history.events.length,7);
  assert.equal(history.events[0].actor_name,'店長一');
  assert.equal(history.events.at(-1).actor_role,'store_manager');
  const list=await call('list');
  assert.equal(list.rows.find(r=>r.id===row.id).lastHandling.name,'總部');
  assert.equal(list.rows.find(r=>r.id===row.id).lastHandling.role,'coo');
  assert.equal(list.rows.find(r=>r.id===row.id).assignee,'維修窗口');
  await assert.rejects(write('update_cost',{id:row.id,version:row.version,note:'門店改費用',cost:0}),/不允許/);
  await user(1);
  for(const cost of [-1,'1.001','NaN','1e3','10000000000']) await assert.rejects(write('update_cost',{id:row.id,version:row.version,note:'錯誤費用',cost}));
  const oldVersion=row.version;
  row=await write('update_cost',{id:row.id,version:row.version,note:'補登收據',cost:'1500.50',cost_note:'零件及工資'});
  assert.equal(row.status,'completed');assert.equal(Number(row.cost),1500.5);
  await assert.rejects(write('update_cost',{id:row.id,version:oldVersion,note:'舊資料',cost:0}),/已更新/);
  const costHistory=(await call('detail',{id:row.id})).events.at(-1);
  assert.equal(Number(costHistory.before_state.cost),500);
  assert.equal(costHistory.after_state.cost_note,'零件及工資');
  await user(2);assert.equal(Number((await call('detail',{id:row.id})).ticket.cost),1500.5);
  const other=await write('create',draft);
  const manifest={id:id(950),name:'gallery.jpg',mime:'image/jpeg',size:100,fingerprint:'b'.repeat(64)};
  const withPhotos=await write('create',{...draft,photo_manifest:[manifest]});
  assert.equal(withPhotos.expected_photos,1);
  await user(1);await assert.rejects(write('start',{id:withPhotos.id,version:1,note:'接手'}),/照片尚未完成/);await user(2);
  const countBeforeBadManifest=(await db.query('select count(*) n from ops_repair_private.tickets')).rows[0].n;
  await assert.rejects(write('create',{...draft,photo_manifest:[{...manifest,id:id(951),mime:'text/html'}]}));
  assert.equal((await db.query('select count(*) n from ops_repair_private.tickets')).rows[0].n,countBeforeBadManifest);
  const photoCall=async(action,payload)=>(await db.query('select public.ops_repair_photo_api($1,$2) result',[action,JSON.stringify(payload)])).rows[0].result;
  const photo={id:id(900),ticketId:other.id,name:'phone.jpg',mime:'image/jpeg',size:100,fingerprint:'a'.repeat(64)};
  await assert.rejects(photoCall('reserve',{...photo,purpose:'receipt'}),/無權/);
  await assert.rejects(photoCall('reserve',{...photo,purpose:'completion'}),/無權/);
  await user(1);
  const receipt=await photoCall('reserve',{...photo,id:id(901),ticketId:row.id,purpose:'receipt'});
  assert.equal(receipt.purpose,'receipt');
  assert.equal((await db.query('select public.ops_repair_photo_access($1,true) ok',[receipt.path])).rows[0].ok,true);
  await assert.rejects(photoCall('reserve',{...photo,id:id(902),ticketId:row.id,purpose:'completion'}),/已結案/);
  await user(2);
  const reserved=await photoCall('reserve',photo);
  assert.equal(reserved.state,'reserved');
  await assert.rejects(photoCall('confirm',photo),/安全驗證/);
  await assert.rejects(photoCall('reserve',{...photo,size:101}),/內容不符/);
  await user(3);
  await assert.rejects(photoCall('list',{ticketId:other.id}),/無權/);
  assert.equal((await db.query('select public.ops_repair_photo_access($1,true) ok',[reserved.path])).rows[0].ok,false);
  await db.exec('set role authenticated');
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name,metadata) values('ops-repair-photos',$1,'{}')",[reserved.path]));
  await db.exec('reset role');
  await user(2);
  await db.exec('set role authenticated');
  await db.query("insert into storage.objects(bucket_id,name,metadata) values('ops-repair-photos',$1,$2)",[reserved.path,JSON.stringify({size:100,mimetype:'image/jpeg'})]);
  await db.exec('reset role');
  assert.equal((await photoCall('reserve',photo)).state,'uploaded');
  await assert.rejects(photoCall('confirm',photo),/安全驗證/);
  const verify = async () => (await db.query('select public.ops_repair_verify_photo($1,$2,$3,$4,$5) result',[photo.id,id(2),photo.fingerprint,photo.mime,photo.size])).rows[0].result;
  assert.equal((await db.query("select has_function_privilege('authenticated','public.ops_repair_verify_photo(uuid,uuid,text,text,bigint)','execute') ok")).rows[0].ok,false);
  assert.equal((await verify()).state,'available');
  assert.equal((await verify()).state,'available');
  assert.equal((await db.query("select count(*) n from ops_repair_private.events where action='photo_confirm'")).rows[0].n,1);
  assert.equal((await db.query('select public.ops_repair_photo_access($1,true) ok',[reserved.path])).rows[0].ok,false);
  await user(3); await db.exec('set role authenticated');
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  await db.exec('reset role'); await user(2);
  assert.equal((await write('withdraw',{id:other.id,version:1,note:'重複回報'})).status,'withdrawn');
  // Force the audit insert to fail after the ticket write; the entire statement must roll back.
  await db.exec(`create function ops_repair_private.fail_event() returns trigger language plpgsql as $$begin raise exception 'audit unavailable'; end$$;
    create trigger fail_event before insert on ops_repair_private.events for each row execute function ops_repair_private.fail_event();`);
  const before=(await db.query('select count(*) n from ops_repair_private.tickets')).rows[0].n;
  await assert.rejects(write('create',draft),/audit unavailable/);
  assert.equal((await db.query('select count(*) n from ops_repair_private.tickets')).rows[0].n,before);
  assert.equal((await db.query("select has_function_privilege('anon','public.ops_repair_api(text,jsonb)','execute') ok")).rows[0].ok,false);
  assert.equal((await db.query("select has_schema_privilege('authenticated','ops_repair_private','usage') ok")).rows[0].ok,false);
 } finally { await db.close(); }
});
